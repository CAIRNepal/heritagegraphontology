#!/usr/bin/env python3
"""Every number the paper reports, as LaTeX macros from the live artefacts.

    python3 scripts/gen_paper_macros.py   # after `make reproduce`

Writes evaluation/heritagegraph-numbers.tex (tracked) with \\newcommand
definitions (e.g. \\hgClasses, \\hgNegativeTests, \\hgCQsPassed). The paper
should \\input this file and use the macros instead of typing numbers, so a
regenerated ontology cannot leave a stale number in the text. Sources: the
released OWL/SHACL, results/metrics.json, results/alignment.json, the CQ and
inference-CQ reports, the mutation analysis, the SSSOM file and the
negative-test suite.
"""
from __future__ import annotations

import ast
import csv
import json
import re
from pathlib import Path

from rdflib import Graph, Namespace, OWL, RDF, RDFS, URIRef

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "evaluation" / "results"
HG = "https://cair-nepal.org/heritagegraph/"
SH = Namespace("http://www.w3.org/ns/shacl#")


def count_negative_tests() -> int:
    tree = ast.parse((ROOT / "evaluation" / "independent_abox.py").read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "tests" for t in node.targets):
            return len(node.value.keys)
    raise SystemExit("negative-test dict not found")


def main() -> int:
    owl = Graph().parse(ROOT / "ontology/HeritageGraph.ttl", format="turtle")
    shacl = Graph().parse(ROOT / "ontology/HeritageGraph.shacl.ttl", format="turtle")
    bridge = Graph().parse(ROOT / "ontology/HeritageGraph-crm-prov-bridge.ttl", format="turtle")
    metrics = json.loads((RES / "metrics.json").read_text())
    alignment = json.loads((RES / "alignment.json").read_text())
    enums = {c for c in owl.subjects(OWL.oneOf, None) if str(c).startswith(HG)}
    classes = metrics["classes_heritagegraph"]          # enumerations are counted apart
    cq_rows = list(csv.DictReader(open(RES / "abox_cq32_report.csv", encoding="utf-8")))
    iq = json.loads((ROOT / "evaluation" / "cq_inference_expected.json").read_text())
    mut = list(csv.DictReader(open(RES / "cq_mutation.csv", encoding="utf-8")))
    sssom = [l for l in (ROOT / "ontology/mappings/HeritageGraph.sssom.tsv").read_text().splitlines()
             if l and not l.startswith("#")][1:]
    abox = Graph().parse(ROOT / "examples/kathmandu-mini-abox.ttl", format="turtle")
    crm_super = sum(1 for c in owl.subjects(RDF.type, OWL.Class) if str(c).startswith(HG)
                    and any(str(o).startswith("http://www.cidoc-crm.org/") for o in owl.objects(c, RDFS.subClassOf)))
    numbers = {
        "OwlTriples": metrics["owl_triples"],
        "Classes": classes,
        "Enumerations": len(enums),
        "ObjectProperties": metrics["object_properties_heritagegraph"],
        "DatatypeProperties": metrics["datatype_properties_heritagegraph"],
        "ClassesUnderCRM": crm_super,
        "MaxCardinality": len(list(owl.subjects(OWL.maxCardinality, None))),
        "PropertyChains": len(list(owl.subjects(OWL.propertyChainAxiom, None))),
        "Deprecated": len(set(owl.subjects(OWL.deprecated, None))),
        "ShaclTriples": len(shacl),
        "NodeShapes": metrics["shacl_node_shapes"],
        "BridgeAxioms": len(list(bridge.subject_objects(RDFS.subClassOf))),
        "SssomMappings": len(sssom),
        "CRMLinkedClasses": alignment["cidoc_crm_hg_classes_linked"],
        "CRMLinkedProperties": alignment["cidoc_crm_hg_properties_linked"],
        "CRMReusedClasses": alignment["cidoc_crm_classes_reused"],
        "CRMReusedProperties": alignment["cidoc_crm_properties_reused"],
        "PROVLinkedClasses": alignment["prov_o_hg_classes_linked"],
        "PROVReusedProperties": alignment["prov_o_properties_reused"],
        "DemonstratorTriples": len(abox),
        "CQs": len(cq_rows),
        "CQsPassed": sum(1 for r in cq_rows if r["status"] == "PASS"),
        "InferenceCQs": len(iq),
        "NegativeTests": count_negative_tests(),
        "Examples": len(list((ROOT / "examples").glob("*.ttl"))),
        "CQSingleWitness": sum(1 for r in mut if r["gold_rows"] == "1"),
        "CQNeedTBox": sum(1 for r in mut if int(r["tbox_axioms_needed"]) > 0),
    }
    for k, v in iq.items():
        numbers[f"{k}Answers"] = len(v["expected"])
    out = ROOT / "evaluation" / "heritagegraph-numbers.tex"
    words = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six",
                                    "Seven", "Eight", "Nine"]))
    lines = ["% Generated by scripts/gen_paper_macros.py from the live artefacts. Do not edit."]
    seen = set()
    for k, v in numbers.items():
        name = "hg" + "".join(words.get(c, c) for c in k if c.isalnum())
        assert name not in seen, f"duplicate macro {name}"
        seen.add(name)
        lines.append(f"\\newcommand{{\\{name}}}{{{v}}}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out.relative_to(ROOT)} ({len(numbers)} macros)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
