#!/usr/bin/env python3
"""Generate cq_sparql.md: one TBox-only SPARQL ASK query per competency question.

The instance-level CQ queries (examples/queries/cq-abox-32.rq) are the single
source: for each CQ, every class, property, and enumeration individual the
query uses is looked up in the released ontology (ontology/HeritageGraph.ttl)
and asserted with its declared OWL type. Each generated ASK is executed against
the TTL before the file is written, so the document cannot drift from the
released vocabulary (the script exits non-zero if any ASK is false). External
terms the TBox does not redeclare (plain CIDOC-CRM / PROV-O / CRMinf
vocabulary) are listed per CQ rather than asserted.

Run: python3 scripts/gen_cq_tbox_doc.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from rdflib import Graph, OWL, RDF, URIRef

ROOT = Path(__file__).resolve().parents[1]
TTL = ROOT / "ontology" / "HeritageGraph.ttl"
QUERIES = ROOT / "examples" / "queries" / "cq-abox-32.rq"
OUT = ROOT / "cq_sparql.md"

TYPE_ORDER = [OWL.Class, OWL.ObjectProperty, OWL.DatatypeProperty, OWL.NamedIndividual]
TYPE_CURIE = {
    OWL.Class: "owl:Class",
    OWL.ObjectProperty: "owl:ObjectProperty",
    OWL.DatatypeProperty: "owl:DatatypeProperty",
    OWL.NamedIndividual: "owl:NamedIndividual",
}
DOC_PREFIXES = {
    "hg": "https://cair-nepal.org/heritagegraph/",
    "crm": "http://www.cidoc-crm.org/cidoc-crm/",
    "crminf": "http://www.cidoc-crm.org/extensions/crminf/",
    "prov": "http://www.w3.org/ns/prov#",
    "owl": "http://www.w3.org/2002/07/owl#",
}
SECTIONS = {1: "Structural", 7: "Ritual/Festival", 19: "Institutional/Syncretic",
            26: "Living Goddess"}


def blocks(text: str) -> list[tuple[int, str, str]]:
    return [(int(m.group(1)), m.group(2).strip(), m.group(3).strip())
            for m in re.finditer(r"^# CQ(\d+): (.*?)\n(.*?)(?=^# CQ\d+:|\Z)",
                                 text, re.M | re.S)]


def terms(sparql: str) -> list[URIRef]:
    prefixes = dict(re.findall(r"PREFIX\s+(\w+):\s*<([^>]+)>", sparql))
    body = re.sub(r"PREFIX\s+\w+:\s*<[^>]+>", "", sparql)
    found: list[URIRef] = []
    for m in re.finditer(r"<(https?://[^>]+)>|\b(\w+):([A-Za-z][\w\-]*)", body):
        if m.group(1):
            iri = m.group(1)
        elif m.group(2) in prefixes:
            iri = prefixes[m.group(2)] + m.group(3)
        else:
            continue
        if URIRef(iri) not in found:
            found.append(URIRef(iri))
    return found


def curie(iri: URIRef) -> str:
    s = str(iri)
    for p, ns in DOC_PREFIXES.items():
        local = s[len(ns):]
        if s.startswith(ns) and re.fullmatch(r"[A-Za-z][\w\-]*", local):
            return f"{p}:{local}"
    return f"<{s}>"


def main() -> int:
    g = Graph()
    g.parse(TTL, format="turtle")
    cqs = blocks(QUERIES.read_text(encoding="utf-8"))
    assert len(cqs) == 32, f"expected 32 CQs, found {len(cqs)}"

    out = [
        "# Competency Questions → TBox-Only SPARQL ASK Queries",
        "",
        "These ASK queries validate that the released ontology "
        "(`ontology/HeritageGraph.ttl`, v1.0.0) declares every class, property, "
        "and enumeration individual each competency question needs. They do "
        "**not** require instance data; the instance-level queries are "
        "`examples/queries/cq-abox-32.rq`, run by `evaluation/run_abox_cq32.py`.",
        "",
        "Generated by `scripts/gen_cq_tbox_doc.py` from the instance-level queries; "
        "every ASK below returns `true` against the released TTL. Do not edit by hand.",
        "",
        "**Prefixes used in all queries**",
        "```sparql",
        *[f"PREFIX {p}: <{ns}>" for p, ns in DOC_PREFIXES.items()],
        "```",
    ]
    failures = []
    for cq, question, sparql in cqs:
        if cq in SECTIONS:
            out += ["", f"**{SECTIONS[cq]} Questions**"]
        declared, external = [], []
        for t in terms(sparql):
            types = [ty for ty in TYPE_ORDER if (t, RDF.type, ty) in g]
            if types:
                declared.append((t, types[0]))
            else:
                external.append(t)
        patterns = [f"  {curie(t)} a {TYPE_CURIE[ty]} ." for t, ty in declared]
        ask = "ASK WHERE {\n" + "\n".join(patterns) + "\n}"
        header = "".join(f"PREFIX {p}: <{ns}>\n" for p, ns in DOC_PREFIXES.items())
        if not g.query(header + ask).askAnswer:
            failures.append(cq)
        out += ["", f"CQ{cq}. {question}", "```sparql", ask, "```"]
        if external:
            out.append("External terms used without an HeritageGraph declaration: "
                       + ", ".join(f"`{curie(t)}`" for t in external) + ".")
    if failures:
        print(f"ASK false for CQ(s) {failures}: the query uses an undeclared term",
              file=sys.stderr)
        return 1
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} (32 TBox ASK queries, all true against {TTL.name})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
